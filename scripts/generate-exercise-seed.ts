// Generates the migration that seeds the exercise library from the pinned
// free-exercise-db commit. Run with `npm run seed:exercises`; it only needs to
// run again if the pinned commit changes, followed by `npx supabase db push`.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { datasetCommit, datasetJsonUrl } from '../src/features/exercises/dataset.ts';
import { toSeedRow, toSqlValues, type DatasetExercise } from './exercise-seed/mapping.ts';

const migration = join(
  import.meta.dirname,
  '..',
  'supabase',
  'migrations',
  '20261008000000_seed_exercise_library.sql',
);

const response = await fetch(datasetJsonUrl);
if (!response.ok) throw new Error(`Could not download the dataset: HTTP ${response.status}`);
const entries = (await response.json()) as DatasetExercise[];
const rows = entries.map(toSeedRow);

const sql = `-- Exercise library seeded from free-exercise-db (https://github.com/yuhonas/free-exercise-db),
-- commit ${datasetCommit}, released under the Unlicense (public domain).
-- Generated by scripts/generate-exercise-seed.ts; edit the script, not this file.
-- ${rows.length} exercises. Library rows have no owner, so every user can read
-- them and nobody can change them (see the exercises policies).

insert into public.exercises
  (source_id, name, exercise_type, primary_muscles, secondary_muscles, equipment, instructions, image_paths)
values
${rows.map(toSqlValues).join(',\n')};
`;

writeFileSync(migration, sql);
const byType = Object.entries(
  rows.reduce<Record<string, number>>((counts, row) => {
    counts[row.exerciseType] = (counts[row.exerciseType] ?? 0) + 1;
    return counts;
  }, {}),
);
console.log(`Wrote ${rows.length} exercises to ${migration}`);
console.log(byType.map(([type, count]) => `  ${type}: ${count}`).join('\n'));
